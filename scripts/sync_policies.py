"""Sync the supported-policy list from the XPolicyLab README into this site.

Rewrites the generated regions of index.html and js/main.js, the policy counts in
index.html, and data/policies.json. Display names and logos already on the site are
kept; new policies take their README name and no logo.

    python3 scripts/sync_policies.py [--readme PATH_OR_URL]
"""
import argparse
import datetime
import hashlib
import html
import json
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README_URL = "https://raw.githubusercontent.com/XPolicyLab/XPolicyLab/main/README.md"
REPO = "https://github.com/XPolicyLab/XPolicyLab/tree/main/policy/"
EXCLUDED = {"demo_policy"}
MIN_POLICIES = 20
PER_ROW = 6

INDEX = ROOT / "index.html"
MAIN_JS = ROOT / "js" / "main.js"
DATA = ROOT / "data" / "policies.json"

TABLE_BEGIN = "<!-- BEGIN POLICY TABLE (generated by scripts/sync_policies.py) -->"
TABLE_END = "<!-- END POLICY TABLE -->"
JS_BEGIN = "// BEGIN POLICIES (generated by scripts/sync_policies.py)"
JS_END = "// END POLICIES"


def read_readme(source):
    if re.match(r"https?://", source):
        with urllib.request.urlopen(source, timeout=60) as response:
            return response.read().decode("utf-8")
    return Path(source).read_text(encoding="utf-8")


def parse_policies(readme):
    section = re.search(r"^## [^\n]*Integrated Policies\n(.*?)(?=^## )", readme, re.M | re.S)
    if not section:
        raise SystemExit("README has no '## ... Integrated Policies' section")
    policies, seen = [], set()
    for line in section.group(1).splitlines():
        if not line.startswith("|"):
            continue
        for name, slug in re.findall(r"\[([^\]]+)\]\(policy/([^/)]+)/README\.md\)", line):
            if slug in EXCLUDED or slug in seen:
                continue
            seen.add(slug)
            policies.append({"name": name, "slug": slug})
    if len(policies) < MIN_POLICIES:
        raise SystemExit(f"Parsed only {len(policies)} policies; refusing to overwrite the site")
    return policies


def replace_between(text, begin, end, body, path):
    start, stop = text.find(begin), text.find(end)
    if start < 0 or stop < start:
        raise SystemExit(f"Generated-region markers are missing in {path}")
    line_start = text.rfind("\n", 0, start) + 1
    indent = text[line_start:start]
    return text[: start + len(begin)] + "\n" + body + indent + text[stop:]


def existing_entries(main_js):
    pattern = r'\{\s*name:\s*("(?:[^"\\]|\\.)*"),\s*slug:\s*"([^"]+)",\s*logo:\s*("(?:[^"\\]|\\.)*"|null)\s*\}'
    return {
        slug: {"name": json.loads(name), "logo": json.loads(logo)}
        for name, slug, logo in re.findall(pattern, main_js)
    }


def render_js(policies):
    lines = []
    for i, p in enumerate(policies):
        comma = "," if i < len(policies) - 1 else ""
        lines.append(
            f"    {{ name: {json.dumps(p['name'], ensure_ascii=False)}, slug: {json.dumps(p['slug'])}, "
            f"logo: {json.dumps(p['logo'])} }}{comma}\n"
        )
    return "".join(lines)


def render_table(policies):
    rows = []
    for i in range(0, len(policies), PER_ROW):
        cells = "".join(
            f'                  <td><a href="{REPO}{html.escape(p["slug"])}" target="_blank" '
            f'rel="noopener noreferrer">{html.escape(p["name"])}</a></td>\n'
            for p in policies[i : i + PER_ROW]
        )
        rows.append(f"                <tr>\n{cells}                </tr>\n")
    return "".join(rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--readme", default=README_URL, help="XPolicyLab README path or URL")
    args = parser.parse_args()

    policies = parse_policies(read_readme(args.readme))
    main_js = MAIN_JS.read_text(encoding="utf-8")
    known = existing_entries(main_js)
    known_ci = {slug.lower(): entry for slug, entry in known.items()}
    for p in policies:
        site = known.get(p["slug"]) or known_ci.get(p["slug"].lower())
        p["name"] = site["name"] if site else p["name"]
        p["logo"] = site["logo"] if site else None
    count = len(policies)

    new_js = replace_between(main_js, JS_BEGIN, JS_END, render_js(policies), MAIN_JS)

    index = INDEX.read_text(encoding="utf-8")
    new_index = replace_between(index, TABLE_BEGIN, TABLE_END, render_table(policies), INDEX)
    new_index = re.sub(r"integrates <strong>\d+</strong> robot policies",
                       f"integrates <strong>{count}</strong> robot policies", new_index)
    new_index = re.sub(r"\d+ policies are currently integrated",
                       f"{count} policies are currently integrated", new_index)
    js_version = hashlib.sha256(new_js.encode("utf-8")).hexdigest()[:8]
    new_index = re.sub(r'js/main\.js\?v=[^"]*"', f'js/main.js?v={js_version}"', new_index)
    if new_index != index:
        month = datetime.datetime.now(datetime.timezone.utc).strftime("%B %Y")
        new_index = re.sub(r"As of [A-Z][a-z]+ \d{4}, the ecosystem",
                           f"As of {month}, the ecosystem", new_index)

    data = json.dumps({"count": count, "policies": policies}, ensure_ascii=False, indent=2) + "\n"

    changed = []
    for path, old, new in [
        (MAIN_JS, main_js, new_js),
        (INDEX, index, new_index),
        (DATA, DATA.read_text(encoding="utf-8") if DATA.exists() else None, data),
    ]:
        if old != new:
            path.write_text(new, encoding="utf-8")
            changed.append(str(path.relative_to(ROOT)))
    print(f"{count} policies; updated: {', '.join(changed) if changed else 'nothing'}")
    for p in policies:
        if p["slug"].lower() not in known_ci:
            print(f"  new: {p['name']} ({p['slug']}) — no logo")


if __name__ == "__main__":
    main()
